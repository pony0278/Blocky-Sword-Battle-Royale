import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entryFile = path.join(repositoryRoot, 'tools', 'action-studio', 'action-studio.js');
const outputFile = path.join(repositoryRoot, 'tools', 'action-studio', 'action-studio.bundle.js');
const htmlTemplateFile = path.join(repositoryRoot, 'tools', 'action-studio', 'index.template.html');
const htmlOutputFile = path.join(repositoryRoot, 'tools', 'action-studio', 'index.html');
const moduleIds = new Map();
const moduleBlocks = [];

function normalizedRelativePath(filename) {
  return path.relative(repositoryRoot, filename).replaceAll(path.sep, '/');
}

async function compileModule(filename) {
  const absoluteFilename = path.resolve(filename);
  if (moduleIds.has(absoluteFilename)) return moduleIds.get(absoluteFilename);

  const moduleId = `__actionStudioModule${moduleIds.size}`;
  moduleIds.set(absoluteFilename, moduleId);
  let source = await readFile(absoluteFilename, 'utf8');
  const imports = [...source.matchAll(/import\s*\{([\s\S]*?)\}\s*from\s*['"]([^'"]+)['"]\s*;/g)];

  for (const match of imports) {
    const specifier = match[2];
    if (!specifier.startsWith('.')) {
      throw new Error(`${normalizedRelativePath(absoluteFilename)} imports unsupported package ${specifier}`);
    }
    const dependencyFile = path.resolve(path.dirname(absoluteFilename), specifier);
    const dependencyId = await compileModule(dependencyFile);
    const bindings = match[1].split(',').map((name) => name.trim()).filter(Boolean).join(', ');
    source = source.replace(match[0], `const { ${bindings} } = ${dependencyId};`);
  }

  const exportNames = [];
  source = source.replace(/\bexport\s+(const|let|var|function|class)\s+([A-Za-z_$][\w$]*)/g, (_match, kind, name) => {
    exportNames.push(name);
    return `${kind} ${name}`;
  });

  if (/\b(?:import|export)\s/.test(source)) {
    throw new Error(`Unsupported ESM syntax remains in ${normalizedRelativePath(absoluteFilename)}`);
  }

  const block = [
    `// ${normalizedRelativePath(absoluteFilename)}`,
    `const ${moduleId} = (() => {`,
    source.trim(),
    `return Object.freeze({ ${exportNames.join(', ')} });`,
    '})();',
  ].join('\n');
  moduleBlocks.push(block);
  return moduleId;
}

await compileModule(entryFile);
const banner = [
  '/* Action Studio standalone bundle.',
  ' * Generated by: npm run build:action-studio',
  ' * Source of truth remains tools/action-studio/action-studio.js and src/.',
  ' * Classic-script output intentionally supports direct file:// opening.',
  ' */',
].join('\n');
const output = `${banner}\n(() => {\n'use strict';\n${moduleBlocks.join('\n\n')}\n})();\n`;
await writeFile(outputFile, output, 'utf8');

const htmlTemplate = await readFile(htmlTemplateFile, 'utf8');
const moduleTag = '<script type="module" src="./action-studio.js"></script>';
const moduleBootstrap = [
  '<script type="module">',
  "    await import('./action-studio.js');",
  "    await import('./studio-combat-feel-controller.js');",
  '  </script>',
].join('\n');
const moduleBootstrapCrlf = moduleBootstrap.split(String.fromCharCode(10)).join(String.fromCharCode(13, 10));
const moduleEntry = htmlTemplate.includes(moduleTag)
  ? moduleTag
  : htmlTemplate.includes(moduleBootstrap)
    ? moduleBootstrap
    : (htmlTemplate.includes(moduleBootstrapCrlf) ? moduleBootstrapCrlf : null);
if (!moduleEntry) {
  throw new Error(`${normalizedRelativePath(htmlTemplateFile)} is missing the expected Action Studio module entry`);
}
const protocolAwareEntry = [
  '<script>',
  "    if (location.protocol === 'file:') {",
  "      document.getElementById('feelAbControls')?.setAttribute('hidden', '');",
  "      const script = document.createElement('script');",
  "      script.src = './action-studio.bundle.js';",
  '      document.body.appendChild(script);',
  '    } else {',
  "      import('./action-studio.js');",
  '    }',
  '  </script>',
].join('\n');
const standaloneHtml = htmlTemplate.replace(moduleEntry, protocolAwareEntry);
await writeFile(htmlOutputFile, standaloneHtml, 'utf8');
console.log(`Built ${normalizedRelativePath(outputFile)} from ${moduleIds.size} ES modules (${output.length} bytes).`);
console.log(`Built ${normalizedRelativePath(htmlOutputFile)} from ${normalizedRelativePath(htmlTemplateFile)}.`);
